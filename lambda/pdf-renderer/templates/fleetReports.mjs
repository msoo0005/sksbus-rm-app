// Fleet exports from Performance & KPIs: "Breakdowns by date range" and
// "Report by bus". No spec of their own yet, so they use the Job Completion
// Report's visual system (same header, footer, greys and type sizes) and the
// contents listed on the app's Export screen.

import {
  DASH, escapeHtml, val, fmtDate, fmtDateTime, fmtGenerated, fmtDuration, fmtOdometer,
  fmtPercent, fmtQty, fmtMonthYear,
} from "../lib/format.mjs";
import { documentHtml, headerHtml, footerHtml, item, template } from "../lib/layout.mjs";

// Bus-system category labels arrive with the data (sksbus-api's
// busSystemInfo), as { key, no, name }; null means uncategorised.
const issueLabel = (info) => (info && info.name ? `${info.no} · ${info.name}` : "Uncategorised");

const CSS = `
.kpis { display: grid; grid-template-columns: repeat(4, 1fr); border: 1px solid #000; }
.kpis > div { padding: 8px 10px; border-right: 1px solid #BDBDBD; }
.kpis > div:last-child { border-right: 0; }
.kpis .k { font-size: 8.5px; font-weight: 700; text-transform: uppercase; letter-spacing: 0.05em; }
.kpis .v { font-size: 16px; font-weight: 700; margin-top: 2px; }
.kpis .s { font-size: 9.5px; margin-top: 1px; }
.bar { height: 10px; background: #D9D9D9; position: relative; }
.bar > span { position: absolute; left: 0; top: 0; bottom: 0; background: #000; }
.rows td { font-size: 10.5px; }
.title-line { font-size: 20px; font-weight: 700; }
.title-line .fleet { font-size: 13px; }
.meta-line { font-size: 11px; margin-top: 2px; }
.small { font-size: 9.5px; }
`;

function sectionHeading(title, note = "") {
  return `<div class="sec"><h2>${title}</h2>${note ? `<span class="note">${note}</span>` : ""}</div>`;
}

function kpiBlock(cells) {
  return `<div class="kpis">${cells.map(([k, v, s]) =>
    `<div><div class="k">${k}</div><div class="v">${v}</div>${s ? `<div class="s">${s}</div>` : ""}</div>`).join("")}</div>`;
}

function issuesTable(issues, total, { repeatFlag = false } = {}) {
  if (!issues?.length) return `<div>No jobs in this period.</div>`;
  return `<table><colgroup><col style="width:200px"><col><col style="width:60px"><col style="width:60px"></colgroup>
    <tr><th>Issue type</th><th></th><th class="num">Jobs</th><th class="num">Share</th></tr>
    ${issues.map((x, i) => `<tr class="${i % 2 === 1 ? "stripe" : ""}">
      <td>${escapeHtml(issueLabel(x.label))}${repeatFlag && x.count >= 2 ? " <b>· repeat</b>" : ""}</td>
      <td><div class="bar"><span style="width:${total ? Math.round((x.count / total) * 100) : 0}%"></span></div></td>
      <td class="num">${x.count}</td><td class="num">${fmtPercent(x.count, total) ?? DASH}</td></tr>`).join("")}
  </table>`;
}

function timeSplitTable(o) {
  const parts = [
    ["Waiting for approval", o.avg_approval_ms],
    ["Waiting to be accepted", o.avg_accept_ms],
    ["Travel to site", o.avg_travel_ms],
    ["Repair on site", o.avg_repair_ms],
  ];
  const sum = parts.reduce((s, [, v]) => s + (v ?? 0), 0);
  return `<table><colgroup><col style="width:200px"><col><col style="width:80px"><col style="width:60px"></colgroup>
    <tr><th>Stage (average job)</th><th></th><th class="num">Time</th><th class="num">Share</th></tr>
    ${parts.map(([k, v], i) => `<tr class="${i % 2 === 1 ? "stripe" : ""}"><td>${k}</td>
      <td><div class="bar"><span style="width:${sum && v ? Math.round((v / sum) * 100) : 0}%"></span></div></td>
      <td class="num">${fmtDuration(v)}</td><td class="num">${fmtPercent(v, sum) ?? DASH}</td></tr>`).join("")}
  </table>`;
}

function bucketsTable(o) {
  const unitLabel = { day: "Day", week: "Week starting", month: "Month" }[o.bucket_unit] ?? "Period";
  return `<table><colgroup><col><col style="width:90px"><col style="width:90px"></colgroup>
    <tr><th>${unitLabel}</th><th class="num">Opened</th><th class="num">Closed</th></tr>
    ${(o.buckets ?? []).map((b, i) => `<tr class="${i % 2 === 1 ? "stripe" : ""}">
      <td>${o.bucket_unit === "month" ? fmtMonthYear(b.start) : fmtDate(b.start)}</td>
      <td class="num">${b.opened}</td><td class="num">${b.closed}</td></tr>`).join("")}
  </table>`;
}

const STATUS = (s) => {
  const v = String(s ?? "").toLowerCase();
  return v === "closed" ? "CLOSED" : v === "open" ? "OPEN" : v === "declined" ? "DECLINED" : "PENDING";
};

const RANGE_COLS = `<colgroup><col style="width:52px"><col style="width:86px"><col style="width:92px"><col><col style="width:96px"><col style="width:70px"><col style="width:92px"></colgroup>`;

export function buildRangeReportHtml(d, { logoHtml, fontCss = "" }) {
  const o = d.overview ?? {};
  const period = `${fmtDate(d.from)} – ${fmtDate(new Date(new Date(d.to).getTime() - 1))}`;
  const head = (sub) => headerHtml({ logoHtml, title: "Breakdown Report", refLabel: "Period", refValue: escapeHtml(period), sub });
  const headers = { first: head(`Generated by ${val(d.generated_by)}`), body: head("continued") };

  const items = [];
  const templates = [];
  const rows = d.rows ?? [];

  items.push(item(sectionHeading("1&nbsp;&nbsp;Summary",
    `${d.bus_ids?.length ? `${d.bus_ids.length} bus${d.bus_ids.length === 1 ? "" : "es"}` : "All buses"} · ${
      d.status === "all" ? "all statuses" : `${d.status} only`}`), { keepNext: true }));
  items.push(item(kpiBlock([
    ["Jobs closed", String(o.jobs_closed ?? 0), `${o.prev_jobs_closed ?? 0} in the previous period`],
    ["Avg turnaround", fmtDuration(o.avg_turnaround_ms), "report → completion"],
    ["Avg approval wait", fmtDuration(o.avg_approval_ms),
      fmtPercent(o.avg_approval_ms, o.avg_turnaround_ms) ? `${fmtPercent(o.avg_approval_ms, o.avg_turnaround_ms)} of turnaround` : ""],
    ["Avg repair time", fmtDuration(o.avg_repair_ms), "on site, per job"],
  ])));

  items.push(item(sectionHeading("2&nbsp;&nbsp;Every breakdown in date order", `${rows.length} report${rows.length === 1 ? "" : "s"}${d.truncated ? " (first 1000)" : ""}`), { keepNext: true }));
  const thead = `<table class="rows">${RANGE_COLS}<tr><th>Report</th><th>Date · time</th><th>Bus</th><th>Issue</th><th>Technician</th><th>Status</th><th class="num">Turnaround</th></tr></table>`;
  templates.push(template("cont-rows", item(sectionHeading("2&nbsp;&nbsp;Every breakdown in date order (continued)"), { tight: true }) + item(thead, { tight: true })));
  items.push(item(thead, { keepNext: true, tight: true }));
  if (!rows.length) items.push(item(`<div>No reports in this period.</div>`));
  rows.forEach((r, i) => {
    items.push(item(`<table class="rows">${RANGE_COLS}<tr class="${i % 2 === 1 ? "stripe" : ""}">
      <td>${r.report_type === "job_order" ? "JO" : "#"}${r.report_id}</td>
      <td>${fmtDateTime(r.reported_at)}</td>
      <td>${escapeHtml(r.bus_id ?? DASH)}${r.bus_ev_no ? ` (${escapeHtml(r.bus_ev_no)})` : ""}</td>
      <td>${val(r.issue)}<div class="small">${escapeHtml(issueLabel(r.issue_label))}</div></td>
      <td>${val(r.technician_name)}</td><td class="b">${STATUS(r.status)}</td>
      <td class="num">${fmtDuration(r.turnaround_ms)}</td></tr></table>`, { tight: true, cont: "cont-rows" }));
  });

  items.push(item(sectionHeading("3&nbsp;&nbsp;Jobs over time"), { keepNext: true }));
  items.push(item(bucketsTable(o)));
  items.push(item(sectionHeading("4&nbsp;&nbsp;Where the time goes"), { keepNext: true }));
  items.push(item(timeSplitTable(o)));
  items.push(item(sectionHeading("5&nbsp;&nbsp;Common issues"), { keepNext: true }));
  items.push(item(issuesTable(o.issues, o.jobs_opened)));

  return documentHtml({
    title: "Breakdown Report",
    css: CSS, fontCss, headers,
    footer: footerHtml(fmtGenerated(d.generated_at)),
    items: items.join("\n"),
    templates: templates.join("\n"),
  });
}

export function buildBusReportHtml(d, { logoHtml, fontCss = "" }) {
  const bus = d.bus ?? {};
  const plate = bus.bus_id ?? DASH;
  const period = d.from ? `${fmtDate(d.from)} – ${fmtDate(d.to)}` : "All time";
  const head = (sub) => headerHtml({ logoHtml, title: "Bus Report", refLabel: "Bus", refValue: `${escapeHtml(plate)}${bus.bus_ev_no ? ` (${escapeHtml(bus.bus_ev_no)})` : ""}`, sub });
  const headers = { first: head(escapeHtml(period)), body: head(`${escapeHtml(plate)} · continued`) };
  const items = [];
  const templates = [];
  const rows = d.rows ?? [];

  items.push(item(`<div class="veh-lbl lbl-caps">Vehicle</div>
    <div class="title-line">${escapeHtml(plate)}${bus.bus_ev_no ? ` <span class="fleet">(${escapeHtml(bus.bus_ev_no)})</span>` : ""}</div>
    <div class="meta-line"><b>${val(bus.bus_model)}</b> · Route ${val(bus.bus_route_number)} ${bus.bus_route ? `· ${escapeHtml(bus.bus_route)}` : ""}</div>
    <div class="meta-line">Latest odometer <b>${fmtOdometer(bus.latest_odometer)}</b> · ${bus.reports_all_time ?? 0} reports all time</div>`));

  items.push(item(sectionHeading("1&nbsp;&nbsp;Totals", escapeHtml(period)), { keepNext: true }));
  items.push(item(kpiBlock([
    ["Jobs", String(d.jobs ?? 0), ""],
    ["Downtime", fmtDuration(d.downtime_ms), "report → fixed, summed"],
    ["Avg turnaround", fmtDuration(d.avg_turnaround_ms), ""],
    ["Reports listed", String(rows.length), d.truncated ? "first 1000" : ""],
  ])));

  items.push(item(sectionHeading("2&nbsp;&nbsp;Issues on this bus", "repeat issues flagged"), { keepNext: true }));
  items.push(item(issuesTable(d.issues, d.jobs, { repeatFlag: true })));

  items.push(item(sectionHeading("3&nbsp;&nbsp;Report history", "oldest first"), { keepNext: true }));
  templates.push(template("cont-hist", item(sectionHeading("3&nbsp;&nbsp;Report history (continued)"))));
  if (!rows.length) items.push(item(`<div>No reports for this bus in this period.</div>`));
  rows.forEach((r) => {
    const work = (r.work_done ?? []).map((w) => {
      const kind = w.job_type === "maintenance" ? "Maintenance" : w.job_type === "repair" ? "Repair" : null;
      const cat = w.category ? `${w.category.no} · ${w.category.name}` : null;
      const tag = [kind, cat].filter(Boolean).join(" · ");
      return `<div><b>${val(w.issue_found)}</b>${tag ? ` <span class="small">(${escapeHtml(tag)})</span>` : ""} — ${val(w.work_done)}${
        w.remark ? ` <i>(Remark: ${escapeHtml(w.remark)})</i>` : ""}</div>`;
    }).join("") || DASH;
    const parts = (r.parts ?? []).map((p) => `${val(p.code)} ${val(p.name)} × ${fmtQty(p.qty)} ${val(p.unit)}`).join("; ") || "None recorded";
    items.push(item(`<div class="box" style="border:1px solid #000">
      <div style="display:flex;justify-content:space-between;background:#D9D9D9;padding:6px 10px;border-bottom:1px solid #000">
        <b>${r.report_type === "job_order" ? "Job order" : "Report"} #${r.report_id}${r.job_ref_no ? ` · ${escapeHtml(r.job_ref_no)}` : ""}</b>
        <span><b>${STATUS(r.status)}</b> · ${fmtDateTime(r.reported_at)}</span></div>
      <table><colgroup><col style="width:110px"><col></colgroup>
        <tr><td class="lbl-caps">Issue</td><td><b>${val(r.issue)}</b> <span class="small">(${escapeHtml(issueLabel(r.issue_label))})</span></td></tr>
        <tr class="stripe"><td class="lbl-caps">Work done</td><td>${work}</td></tr>
        <tr><td class="lbl-caps">Parts used</td><td>${parts}</td></tr>
        <tr class="stripe"><td class="lbl-caps">Technician</td><td>${val(r.technician_name)}</td></tr>
        <tr><td class="lbl-caps">Turnaround</td><td>${fmtDuration(r.turnaround_ms)}</td></tr>
      </table></div>`, { cont: "cont-hist" }));
  });

  return documentHtml({
    title: "Bus Report",
    css: CSS, fontCss, headers,
    footer: footerHtml(fmtGenerated(d.generated_at)),
    items: items.join("\n"),
    templates: templates.join("\n"),
  });
}
